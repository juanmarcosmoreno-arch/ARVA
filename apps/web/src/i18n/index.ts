export const dictionaries = { en, es } as const;

export type TranslationVars = Record<string, string | number>;

/** Replace {name} placeholders; unknown placeholders are left visible rather than dropped. */
export function interpolate(text: string, vars?: TranslationVars) {
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match));
}

export function useT() {
  const language = useSettings((s) => s.language);
  return (key: TranslationKey, vars?: TranslationVars) => interpolate(dictionaries[language][key] ?? en[key], vars);
}
