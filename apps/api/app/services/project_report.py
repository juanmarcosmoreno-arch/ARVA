def _latest(db: Session, model, sample_id: str):
    return db.scalar(select(model).where(model.sample_id == sample_id).order_by(model.created_at.desc()).limit(1))


def _latest_job(db: Session, sample_id: str, job_type: str, method: str | None = None) -> AnalysisJob | None:
    for j in db.scalars(select(AnalysisJob).where(AnalysisJob.sample_id == sample_id, AnalysisJob.job_type == job_type,
                                                  AnalysisJob.status == JobStatus.completed)
                        .order_by(AnalysisJob.created_at.desc())):
        if method is None or (j.parameters or {}).get("method") == method:
            return j
    return None


def _versions(j: AnalysisJob | None) -> dict[str, Any] | None:
    if j is None:
        return None
    return {"tool": j.tool_name, "tool_version": j.tool_version, "database": j.database_name,
            "database_version": j.database_version}


def _assembly_of(job: AnalysisJob | None) -> str | None:
    return ((job.parameters or {}).get("assembly") or {}).get("assembly_id") if job is not None else None


def _sample(db: Session, s: Sample, qc: dict[str, Any] | None) -> dict[str, Any]:
    """The sample's latest result of each analysis, each with the assembly it was computed on (`assembly_id`);
    `mixed_assemblies` is set when they are not all from the assembly shown (as Discover flags it)."""
    a = db.scalar(select(Assembly).where(Assembly.sample_id == s.id).order_by(Assembly.created_at.desc()).limit(1))
    sp, m = _latest(db, SpeciesResult, s.id), _latest(db, MlstResult, s.id)
    amr_job = _latest_job(db, s.id, AMR_JOB)
    vf_job = _latest_job(db, s.id, VIRULENCE_JOB)
    rep_job = _latest_job(db, s.id, MOBILE_JOB, "plasmidfinder")
    typing = {}
    for t in db.scalars(select(TypingResult).where(TypingResult.sample_id == s.id)
                        .order_by(TypingResult.created_at.desc())):
        typing.setdefault(t.method, {"module": t.module, "method": t.method, "status": t.status, "call": t.call,
                                     "tool": t.tool, "tool_version": t.tool_version, "assembly_id": t.assembly_id,
                                     **_typing_extra(t)})
    st = a.stats if a else {}
    amr = None
    if amr_job is not None:
        rows = db.scalars(select(AmrResult).where(AmrResult.job_id == amr_job.id, AmrResult.type == "AMR")
                          .order_by(AmrResult.element_symbol)).all()
        p = amr_job.parameters or {}
        amr = {**_versions(amr_job), "assembly_id": _assembly_of(amr_job),
               "genes": sorted({r.element_symbol for r in rows}),
               "classes": sorted({r.amr_class for r in rows if r.amr_class}),
               # The options that decide what can be found: a nucleotide-only search runs no HMMs, and point
               # mutations are searched only with an organism.
               "mode": p.get("mode") or "nucleotide", "organism": p.get("organism"), "plus": bool(p.get("plus"))}
    used = {x for x in (_assembly_of(amr_job), _assembly_of(vf_job), _assembly_of(rep_job),
                        sp.assembly_id if sp else None, m.assembly_id if m else None,
                        *(t["assembly_id"] for t in typing.values())) if x}
    return {
        "mixed_assemblies": bool(used - {a.id if a else None}),
        "id": s.id, "code": s.sample_code, "organism": s.organism, "expected_species": s.expected_species,
        "host": s.host, "country": s.geographic_origin, "collection_date": s.collection_date.isoformat()
        if s.collection_date else None, "source": s.sample_type, "technology": s.sequencing_technology.value,
        "qc": None if qc is None or qc.get("total_reads") is None else {
            k: qc.get(k) for k in ("total_reads", "total_bases", "n50", "mean_read_quality", "q30_percent",
                                   "gc_percent", "estimated_depth", "stats_tool_versions")},
        "assembly": None if a is None else {
            "id": a.id, "assembler": a.assembler, "assembler_version": a.assembler_version, "kind": a.kind.value,
            "contigs": st.get("contig_count"), "total_length": st.get("total_length"), "n50": st.get("n50"),
            "gc_percent": st.get("gc_percent"), "warnings": len(a.warnings or [])},
        "species": None if sp is None else {"species": sp.species, "status": sp.status, "method": sp.method,
                                            "assembly_id": sp.assembly_id,
                                            "tool": sp.tool, "tool_version": sp.tool_version,
                                            "database": sp.database_name, "database_version": sp.database_version},
        "mlst": None if m is None else {"scheme": m.scheme, "st": m.st, "status": m.status, "tool": m.tool,
                                        "assembly_id": m.assembly_id,
                                        "tool_version": m.tool_version, "database_version": m.database_version,
                                        "clonal_complex": (m.clonal_complex or {}).get("value")},
        "amr": amr,
        "virulence": None if vf_job is None else {**_versions(vf_job), "assembly_id": _assembly_of(vf_job),
                                                  **_vfdb(db, vf_job)},
        "replicons": None if rep_job is None else {**_versions(rep_job), "assembly_id": _assembly_of(rep_job),
                                                   "replicons": sorted(set(db.scalars(
            select(MobileElementResult.element).where(MobileElementResult.job_id == rep_job.id,
                                                      MobileElementResult.category == "replicon"))))},
        "typing": list(typing.values()),
    }


def _vfdb(db: Session, vf_job: AnalysisJob) -> dict[str, Any]:
    """The screen's genes, with the hits the combined virulence view flags as probably another gene (VFDB lukF-PV on
    AMRFinderPlus's lukD region) listed apart as cross-hits, and which VFDB it searched (set A core or B full, and its
    version)."""
    found = vfdb_genes(db, vf_job)
    v = vfdb_of(vf_job)
    return {"genes": found["genes"], "cross_hits": found["cross_hits"], "vfdb_set": v.get("set"),
            "vfdb_dataset": v.get("dataset"), "vfdb_version": v.get("version")}


def _vfdb_label(section: dict[str, Any], lang: str = "en") -> str:
    """'VFDB core (set A) 2026-04-03' / 'VFDB full (set B) 2026-11-06' for a sample's virulence column."""
    return set_label({"set": section.get("vfdb_set"), "name": section.get("database"),
                      "version": section.get("vfdb_version") or section.get("database_version")}, lang)


def _typing_extra(t: TypingResult) -> dict[str, Any]:
    """agr with k-mers of several groups: each group's k-mer hits (AgrVATE's majority group is the call, if any)."""
    if t.method != "agr" or t.status != "multiple":
        return {}
    from app.services.staph_typing import agr_counts_text

    return {"kmer_counts": agr_counts_text(t.details or {}) or None,
            "agrvate_group": (t.details or {}).get("agr_group")}


def typing_text(t: dict[str, Any]) -> str:
    """A typing step's result as the report prints it: the call, or the status; agr with several groups also gives
    each group's k-mer hits ("I (multiple: I 15, II 13)")."""
    if t.get("method") == "agr" and t.get("status") == "multiple":
        if t.get("kmer_counts"):
            return f"{t['call'] or 'not determined'} (multiple: {t['kmer_counts']})"
        return f"multiple (AgrVATE: {t.get('agrvate_group') or '?'}; k-mer counts not read)"
    return t["call"] or t["status"]


def amr_options_text(amr: dict[str, Any]) -> str:
    """The AMRFinderPlus options a reader needs to compare results: the search and the organism."""
    return f"{amr.get('mode') or 'nucleotide'} search, organism {(amr.get('organism') or 'none').replace('_', ' ')}"


def _citations() -> dict[str, dict[str, str]]:
    out = {}
    for tool_id, adapter in ADAPTERS.items():
        info = adapter.info
        for key in {tool_id.lower(), info.name.lower(), info.executable.lower()}:
            out[key] = {"name": info.name, "citation": info.citation, "url": info.citation_url}
    return out


def _methods(db: Session, project: Project, comparisons: list[dict[str, Any]]) -> list[dict[str, Any]]:
    cites = _citations()
    tools: dict[str, dict[str, Any]] = {}

    def add(name: str, version: str | None, used_for: str, database: str | None = None) -> None:
        if not name:
            return
        c = cites.get(name.lower()) or cites.get(name.lower().split()[0]) or {}
        t = tools.setdefault(c.get("name") or name, {"tool": c.get("name") or name, "versions": set(),
                                                     "used_for": set(), "databases": set(),
                                                     "citation": c.get("citation"), "citation_url": c.get("url")})
        if version:
            t["versions"].add(version)
        t["used_for"].add(used_for)
        if database:
            t["databases"].add(database)

    for j in db.scalars(select(AnalysisJob).where(AnalysisJob.project_id == project.id,
                                                  AnalysisJob.status == JobStatus.completed)):
        db_text = " ".join(x for x in (j.database_name, j.database_version) if x) or None
        add(j.tool_name, j.tool_version, j.job_type, db_text)
    for cset in comparisons:
        for r in cset["results"]:
            add(r["tool"], r["tool_version"], f"comparative:{r['analysis']}")
    return [{**t, "versions": sorted(t["versions"]), "used_for": sorted(t["used_for"]),
             "databases": sorted(t["databases"])} for t in sorted(tools.values(), key=lambda t: t["tool"].lower())]


def _comparisons(db: Session, project: Project) -> list[dict[str, Any]]:
    out = []
    for s in comparative_svc.list_sets(db, project.id):
        results = [{"id": r.id, "analysis": r.analysis, "method": r.method, "tool": r.tool,
                    "tool_version": r.tool_version, "genomes": len(r.genomes or []),
                    "created_at": r.created_at.isoformat(timespec="seconds"), "warnings": len(r.warnings or [])}
                   for r in db.scalars(select(ComparisonResult).where(ComparisonResult.set_id == s["id"])
                                       .order_by(ComparisonResult.created_at))]
        out.append({"id": s["id"], "name": s["name"], "genomes": s["genomes"], "labels": s["labels"],
                    "results": results})
    return out


def collect(db: Session, project: Project, lang: str = "en") -> dict[str, Any]:
    samples = list(db.scalars(select(Sample).where(Sample.project_id == project.id).order_by(Sample.sample_code)))
    qc = {r["sample_id"]: r for r in build_overview(db, project.id)}
    comparisons = _comparisons(db, project)
    rows = [_sample(db, s, qc.get(s.id)) for s in samples]
    return {
        "report": "project", "arva_version": ARVA_VERSION, "language": lang,
        "generated_at": datetime.now(UTC).isoformat(timespec="seconds"),
        "project": {"id": project.id, "name": project.name, "description": project.description,
                    "is_demo": project.is_demo, "samples": len(samples)},
        "scope": LABELS["en"]["scope"],
        "samples": rows, "comparisons": comparisons, "methods": _methods(db, project, comparisons),
        "limitations": LIMITATIONS["en"],
        "counts": {"with_assembly": sum(1 for r in rows if r["assembly"]),
                   "with_species": sum(1 for r in rows if r["species"]),
                   "with_mlst": sum(1 for r in rows if r["mlst"]),
                   "amr_searched": sum(1 for r in rows if r["amr"] is not None),
                   "comparison_sets": len(comparisons)},
    }


