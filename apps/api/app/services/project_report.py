def render_csv(data: dict[str, Any]) -> str:
    out = io.StringIO()
    w = csv.DictWriter(out, fieldnames=CSV_COLUMNS)
    w.writeheader()

    def safe(v: Any) -> Any:
        text = "" if v is None else str(v)
        return "'" + text if text[:1] in ("=", "+", "-", "@", "\t", "\r") and not text[1:2].isdigit() else text

    for r in data["samples"]:
        q, a, sp, m = r["qc"] or {}, r["assembly"] or {}, r["species"] or {}, r["mlst"] or {}
        row = {
            "sample": r["code"], "organism": r["organism"], "host": r["host"], "origin": r["country"],
            "collection_date": r["collection_date"], "sample_type": r["source"], "technology": r["technology"],
            "reads": q.get("total_reads"), "bases": q.get("total_bases"), "read_n50": q.get("n50"),
            "mean_read_quality": q.get("mean_read_quality"), "q30_percent": q.get("q30_percent"),
            "assembler": a.get("assembler"), "assembler_version": a.get("assembler_version"),
            "assembly_kind": a.get("kind"), "contigs": a.get("contigs"), "total_length": a.get("total_length"),
            "n50": a.get("n50"), "gc_percent": a.get("gc_percent"), "species": sp.get("species"),
            "species_tool": f"{sp['tool']} {sp['tool_version']}" if sp else None,
            "mlst": f"{m['scheme']}:{m['st']}" if m and m.get("st") else (m.get("status") if m else None),
            "mlst_tool": f"{m['tool']} {m['tool_version']}" if m else None,
            "amr_genes": "not searched" if r["amr"] is None else ";".join(r["amr"]["genes"]),
            "amr_tool": f"{r['amr']['tool']} {r['amr']['tool_version']} / {r['amr']['database_version']} "
                        f"({amr_options_text(r['amr'])})" if r["amr"] else None,
            "virulence_genes": "not searched" if r["virulence"] is None else ";".join(r["virulence"]["genes"]),
            "virulence_cross_hits": None if r["virulence"] is None else ";".join(
                cross_hit_text(c) for c in r["virulence"]["cross_hits"]),
            "virulence_vfdb": None if r["virulence"] is None else _vfdb_label(r["virulence"]),
            "replicons": "not searched" if r["replicons"] is None else ";".join(r["replicons"]["replicons"]),
            "typing": ";".join(f"{t['method']}={typing_text(t)}" for t in r["typing"]),
            "assembly_id": a.get("id"), "mixed_assemblies": "yes" if r.get("mixed_assemblies") else "no",
        }
        w.writerow({k: safe(v) for k, v in row.items()})
    return out.getvalue()


def _no_fetch(url: str, *args: Any, **kwargs: Any) -> dict:
    raise ValueError(f"ARVA reports load nothing from outside the document ({url[:40]})")


def render_pdf(html: str) -> bytes:
    """WeasyPrint (BSD-3-Clause) renders the HTML and its inline SVG; every external resource is refused, so the
    PDF is made from the report's own content only."""
    from weasyprint import HTML

    return HTML(string=html, url_fetcher=_no_fetch).write_pdf()


def pdf_available() -> bool:
    try:
        import weasyprint  # noqa: F401
    except (ImportError, OSError):
        return False
    return True
