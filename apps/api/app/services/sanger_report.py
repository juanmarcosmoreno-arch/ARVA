def code_text(item: dict[str, Any], lang: str) -> str:
    template = CODES[lang].get(item.get("code", ""))
    if template is None:
        return str(item.get("code"))
    params = {k: _fmt_param(v, lang) for k, v in (item.get("params") or {}).items()}
    try:
        return render(template, params)
    except (KeyError, ValueError, IndexError):
        return str(item.get("code"))


def _fmt_param(v: Any, lang: str) -> Any:
    if isinstance(v, float):
        return _num(v, lang, 2)
    if isinstance(v, list):
        return ", ".join(str(x) for x in v)
    return v


def _num(v: Any, lang: str, digits: int = 0) -> str:
    if v is None:
        return "–"
    if isinstance(v, bool) or not isinstance(v, int | float):
        return str(v)
    text = f"{v:,.{digits}f}"
    return text.replace(",", " ").replace(".", ",") if lang == "es" else text


def _cell(v: Any) -> str:
    return escape("–" if v in (None, "") else str(v))


def collect(db: Session, ident: SangerIdentification) -> dict[str, Any]:
    sample = db.get(Sample, ident.sample_id)
    project = db.get(Project, sample.project_id) if sample else None
    data = svc.results(db, ident)
    return {"report": "sanger_identification", "generated_at": datetime.now(UTC).isoformat(timespec="seconds"),
            "arva_version": __version__,
            "sample": {"id": sample.id, "code": sample.sample_code, "organism": sample.organism} if sample else None,
            "project": {"id": project.id, "name": project.name} if project else None, **data}


def render_json(data: dict[str, Any]) -> str:
    return json.dumps(data, indent=2, default=str)


def _name(r: dict[str, Any]) -> str:
    bits = [r.get("gene"), r.get("species"), r.get("product") if not r.get("species") else None]
    if r.get("allele"):
        bits.append(f"allele {r['allele']}")
    return " · ".join(str(b) for b in bits if b) or (r.get("title") or r.get("subject") or "")


def render_csv(data: dict[str, Any]) -> str:
    """One row per ranked hit (every source searched), with the database and version of its source."""
    out = io.StringIO()
    w = csv.writer(out, lineterminator="\n")
    w.writerow(["identification", "rank", "tied_with_best", "source", "database", "database_version", "subject",
                "title", "gene", "species", "product", "allele", "genome", "identity_percent", "identical",
                "aligned_length", "query_coverage_percent", "subject_coverage_percent", "query_start", "query_end",
                "subject_start", "subject_end", "strand", "kind", "evalue", "bitscore", "copies"])
    label = data["identification"]["label"]
    for r in data["ranked"]:
        src = r.get("source") or {}
        w.writerow([label, r.get("rank"), r.get("tied_with_best"), src.get("source"), src.get("name"),
                    src.get("version"), r.get("subject"), r.get("title"), r.get("gene"), r.get("species"),
                    r.get("product"), r.get("allele"), r.get("genome"), round(r["identity"], 4), r.get("identical"),
                    r.get("aligned_length"), round(r["query_coverage"], 4), round(r["subject_coverage"], 4),
                    r.get("query_start"), r.get("query_end"), r.get("subject_start"), r.get("subject_end"),
                    r.get("strand"), r.get("kind"), r.get("evalue"), r.get("bitscore"), r.get("copies")])
    return out.getvalue()


def _reads_html(data: dict[str, Any], L: dict[str, str], lang: str) -> str:
    rows = []
    trims = data["identification"]["settings"]
    for role in ("forward", "reverse"):
        r = data["reads"].get(role)
        if not r:
            continue
        s = r["summary"] or {}
        inst = s.get("instrument") or {}
        trim = trims.get(f"{role}_trim") or {}
        kept = (data["consensus"].get(role) or data["consensus"].get("read") or {}).get("trim") \
            if data["identification"]["mode"] == "pair" else (data["consensus"].get("read") or {}).get("trim")
        kept_text = f"{kept['start']}–{kept['end']} ({_num(kept['length'], lang)})" if kept and kept.get("start") \
            else "–"
        method = (kept or {}).get("method") or "–"
        limit = trim.get("limit") if method == "modified_mott" else None
        rows.append(f"<tr><td>{L[role]}</td><td>{_cell(r['name'])}</td><td>{_cell(r['original_filename'])}</td>"
                    f"<td>{_cell(r['file_format'])}</td><td>{_num(r['length'], lang)}</td>"
                    f"<td>{_cell(inst.get('model'))}</td><td>{_cell(inst.get('basecaller'))}</td>"
                    f"<td>{_num(s.get('mean_quality'), lang, 1)}</td><td>{_num(s.get('q20_percent'), lang, 1)}</td>"
                    f"<td>{_cell(method)}{f' ({_num(limit, lang, 2)})' if limit else ''}</td><td>{kept_text}</td></tr>")
    return (f"<table><tr><th>{L['direction']}</th><th>{L['read']}</th><th>{L['file']}</th><th>{L['format']}</th>"
            f"<th>{L['length']}</th><th>{L['instrument']}</th><th>{L['basecaller']}</th><th>{L['mean_q']}</th>"
            f"<th>{L['q20']}</th><th>{L['trim_method']}</th><th>{L['kept']}</th></tr>{''.join(rows)}</table>")


def _consensus_html(data: dict[str, Any], L: dict[str, str], lang: str) -> str:
    c = data["consensus"]
    ident = data["identification"]
    mode = L["mode_pair"] if ident["mode"] == "pair" else L["mode_single"]
    parts = [f"<p><b>{mode}</b>: {_num(ident['length'], lang)} {L['length'].lower()} · SHA-256 "
             f"<code>{escape(ident['sha256'])}</code></p>"]
    if ident["mode"] == "pair":
        o = c.get("overlap") or {}
        parts.append(f"<p>{L['overlap']}: {_num(o.get('columns'), lang)} {L['columns']}, {L['identity']} "
                     f"{_num(o.get('identity'), lang, 2)}, {_num(o.get('mismatches'), lang)} {L['mismatches']}, "
                     f"{_num(o.get('gaps'), lang)} {L['gaps']}</p>")
        conflicts = c.get("conflicts") or []
        if conflicts:
            body = "".join(
                f"<tr><td>{x['column']}</td><td>{_cell(x['position'])}</td>"
                f"<td>{_cell((x.get('forward') or {}).get('base') or '-')} "
                f"(Q{_cell((x.get('forward') or {}).get('quality'))})</td>"
                f"<td>{_cell((x.get('reverse') or {}).get('base') or '-')} "
                f"(Q{_cell((x.get('reverse') or {}).get('quality'))})</td><td>{_cell(x['base'] or '-')}</td>"
                f"<td>{_cell(x['status'])}</td><td>{_cell(x['rule'])}</td></tr>" for x in conflicts[:200])
            parts.append(f"<h3>{L['conflicts']} ({len(conflicts)})</h3><table><tr><th>{L['column']}</th>"
                         f"<th>{L['position']}</th><th>{L['forward']}</th><th>{L['reverse']}</th><th>{L['result']}</th>"
                         f"<th>{L['status']}</th><th>{L['rule']}</th></tr>{body}</table>")
        else:
            parts.append(f"<p>{L['conflicts']}: {L['none']}</p>")
        params = c.get("params") or {}
        parts.append(f"<p class='muted'>{L['parameters']}: " + escape(", ".join(f"{k} = {v}" for k, v in
                                                                                params.items())) + "</p>")
    for w in c.get("warnings") or []:
        parts.append(f"<p class='warn'>{escape(code_text(w, lang))}</p>")
    return "".join(parts)


